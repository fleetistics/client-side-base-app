#!/usr/bin/env node
/**
 * `pnpm release-app`: refuses to run with uncommitted changes, then writes the short git commit hash
 * to app-hash.local.ts (gitignored). The app reads it via the `@app-hash` alias (see babel.config.js),
 * so a release build is always traceable to an exact commit.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const HASH_FILE = path.join(__dirname, '..', 'app-hash.local.ts');
const ROOT = path.join(__dirname, '..');

function git(...args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
}

// Includes staged, unstaged, untracked (non-ignored) files and modified submodules.
const dirty = git('status', '--porcelain');
if (dirty) {
  console.error('release-app: working tree has uncommitted changes, commit or stash them first:\n');
  console.error(dirty);
  process.exit(1);
}

const hash = git('rev-parse', '--short', 'HEAD');
fs.writeFileSync(
  HASH_FILE,
  `// Generated by scripts/release-app.js. Gitignored, do not edit.\nexport const APP_HASH = "${hash}";\n`,
);
console.log(`release-app: APP_HASH=${hash} written to ${path.basename(HASH_FILE)}`);
